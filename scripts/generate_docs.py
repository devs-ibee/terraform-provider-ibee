#!/usr/bin/env python3
"""Generate registry schema pages from the compiled provider, offline.

Requires Go, Terraform >=1.11, Python >=3.9. No IBEE credentials are used.
Use --check to verify checked-in docs and validate every example configuration.
"""
import argparse
import json
import os
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
ADDRESS = "registry.terraform.io/devs-ibee/ibee"
EXAMPLES = ROOT / "examples"
# Per-page examples: examples/<category>/<name>/{resource.tf,data-source.tf,action.tf,import.sh}.
SNIPPETS = {"resources": "resource.tf", "data-sources": "data-source.tf", "actions": "action.tf"}
PROVIDER_BLOCK = 'terraform {\n  required_providers {\n    ibee = { source = "devs-ibee/ibee" }\n  }\n}\n\n'


def snippet(category, name, filename):
    path = EXAMPLES / category / name / filename
    if not path.exists():
        raise SystemExit(f"Missing {path.relative_to(ROOT)}; every {category} page needs it.")
    return path.read_text().strip()


def run(args, cwd, env):
    result = subprocess.run(args, cwd=cwd, env=env, text=True, capture_output=True)
    if result.returncode:
        raise RuntimeError(f"{' '.join(args)} failed:\n{result.stdout}\n{result.stderr}")
    return result.stdout


def type_name(value):
    if isinstance(value, str):
        return value
    if isinstance(value, list):
        if value[0] == "object":
            return "object"
        return f"{value[0]}({type_name(value[1])})"
    return "object"


def schema_lines(attributes, prefix=""):
    rows = []
    for name, attr in sorted(attributes.items()):
        full = prefix + name
        nested = attr.get("nested_type")
        kind = f"{nested['nesting_mode']}(object)" if nested else type_name(attr.get("type"))
        flags = [label for key, label in [("required", "Required"), ("optional", "Optional"), ("computed", "Read-only"), ("sensitive", "Sensitive"), ("write_only", "Write-only")] if attr.get(key)]
        if attr.get("optional") and attr.get("computed"):
            flags.remove("Read-only")
            flags.append("Defaulted")
        description = attr.get("description", "").replace("|", "\\|").replace("\n", " ")
        rows.append(f"| `{full}` | `{kind}` | {', '.join(flags)} | {description} |")
        if nested:
            rows.extend(schema_lines(nested["attributes"], full + "."))
    return rows


def page(name, block, category):
    label = {"provider": "Provider", "resources": "Resource", "data-sources": "Data Source", "actions": "Action"}[category]
    description = block.get("description", "Manage IBEE cloud resources.")
    text = ["---", 'page_title: "' + name + ' ' + label + ' - IBEE"', 'subcategory: ""', "description: |-", "  " + description.replace("\n", "\n  "), "---", "", f"# {name} ({label})", "", description, "", "<!-- Generated by scripts/generate_docs.py; edit schema descriptions in Go. -->", ""]
    if category == "provider":
        text += ["Terraform 1.11 or newer is required. Set `IBEE_TOKEN` and `IBEE_WORKSPACE_ID` in the environment.", "", '```hcl', 'terraform {', '  required_version = ">= 1.11.0"', '  required_providers {', '    ibee = { source = "devs-ibee/ibee" }', '  }', '}', '', 'provider "ibee" {}', '```', "", "Start with the [Terraform guide](guides/terraform.md), or browse the [examples](../examples/README.md).", ""]
    if category in SNIPPETS:
        text += ["## Example Usage", "", "```terraform", snippet(category, name, SNIPPETS[category]), "```", ""]
    text += ["## Schema", "", "| Attribute | Type | Behavior | Description |", "| --- | --- | --- | --- |"]
    text += schema_lines(block.get("attributes", {}))
    if category == "actions":
        text += ["", "Requires Terraform 1.14 or later. Configure this action in an `action` block with a nested `config` block. Invoke explicitly with `terraform apply -invoke=action." + name + ".example`. Actions perform operations without storing a managed resource."]
    if category == "resources":
        text += ["", "## Import", "", "Import an existing resource with the identifier shown. Review the imported plan before applying; creation-only settings and local deletion permissions cannot always be reconstructed from the API.", "", "```shell", snippet(category, name, "import.sh"), "```"]
    text += [""]
    return "\n".join(text)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    env = {k: v for k, v in os.environ.items() if not k.startswith(("IBEE_", "TF_"))}
    env.update(TF_IN_AUTOMATION="1", CHECKPOINT_DISABLE="1")
    version = json.loads(run(["terraform", "version", "-json"], ROOT, env))["terraform_version"]
    supports_actions = tuple(int(v) for v in version.split(".")[:2]) >= (1, 14)
    with tempfile.TemporaryDirectory(prefix="ibee-docs-") as temp:
        tmp = Path(temp)
        binary = tmp / "bin" / "terraform-provider-ibee"
        binary.parent.mkdir()
        run(["go", "build", "-buildvcs=false", "-o", str(binary), "."], ROOT, env)
        config = tmp / "dev.tfrc"
        config.write_text('provider_installation {\n dev_overrides { "devs-ibee/ibee" = ' + json.dumps(str(binary.parent)) + ' }\n direct {}\n}\n')
        env["TF_CLI_CONFIG_FILE"] = str(config)
        (tmp / "main.tf").write_text('terraform {\n required_providers { ibee = { source = "devs-ibee/ibee" } }\n}\n')
        schema = json.loads(run(["terraform", "providers", "schema", "-json"], tmp, env))["provider_schemas"][ADDRESS]
        expected = {ROOT / "docs" / "index.md": page("ibee", schema["provider"]["block"], "provider")}
        for key, category in [("resource_schemas", "resources"), ("data_source_schemas", "data-sources")]:
            for name, spec in schema.get(key, {}).items():
                expected[ROOT / "docs" / category / (name.removeprefix("ibee_") + ".md")] = page(name, spec["block"], category)
        stale = []
        if supports_actions:
            for name, entry in schema.get("action_schemas", {}).items():
                expected[ROOT / "docs" / "actions" / (name.removeprefix("ibee_") + ".md")] = page(name, entry["block"], "actions")
        for path, contents in expected.items():
            if args.check:
                if not path.exists() or path.read_text() != contents:
                    stale.append(str(path.relative_to(ROOT)))
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(contents)
        for directory in (ROOT / "docs/resources", ROOT / "docs/data-sources"):
            for path in directory.glob("*.md"):
                if path not in expected:
                    stale.append(str(path.relative_to(ROOT)))
        categories = [("resources", "resource_schemas"), ("data-sources", "data_source_schemas")]
        if supports_actions:
            categories.append(("actions", "action_schemas"))
        for category, key in categories:
            for directory in (EXAMPLES / category).iterdir():
                if directory.is_dir() and directory.name not in schema.get(key, {}):
                    stale.append(str(directory.relative_to(ROOT)))
        if stale:
            raise SystemExit("Documentation differs; run make docs and review: " + ", ".join(stale))
        snippet_roots = [EXAMPLES / category for category in SNIPPETS]
        for directory in sorted({p.parent for p in EXAMPLES.rglob("*.tf")}):
            actions = EXAMPLES / "actions"
            if not supports_actions and (directory == actions or actions in directory.parents):
                continue
            if any(root in directory.parents for root in snippet_roots):
                # Page examples are fragments; validate each with a provider block.
                work = tmp / "snippets" / directory.parent.name / directory.name
                work.mkdir(parents=True)
                (work / "main.tf").write_text(PROVIDER_BLOCK + "".join(p.read_text() for p in sorted(directory.glob("*.tf"))))
                run(["terraform", "validate", "-no-color"], work, env)
                continue
            run(["terraform", "validate", "-no-color"], directory, env)
        print(f"{'Checked' if args.check else 'Generated'} {len(expected)} schema pages; validated examples.")


if __name__ == "__main__":
    main()
